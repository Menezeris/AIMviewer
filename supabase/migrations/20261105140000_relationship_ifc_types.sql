-- Every listed type is an IFC entity of the manifest.
do $$
declare bad text;
begin
  select string_agg(distinct t, ', ') into bad
    from relationship_types m, unnest(m.from_ifc_types || m.to_ifc_types) t
   where not exists (select 1 from entity_types e where e.ifc_class = t);
  if bad is not null then
    raise exception 'D-196: IFC end types not in entity_types: %', bad;
  end if;
end $$;

