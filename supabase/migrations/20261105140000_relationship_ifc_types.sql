-- D-196 (R10, PR 1): IFC types of both relationship ends in the manifest, and a report of the edges that
-- would fail the IFC rule. No write behaviour changes: relationships_validate is untouched and ifc_check is
-- 'off' for every rel_type. PR 3 adds the check to the trigger ('warn', then 'enforce' per rel_type).
--
--   * relationship_types.from_ifc_types / to_ifc_types: the declared IFC type of the From / To end (the
--     Relating* and Related* attribute of the IfcRel class, a SELECT expanded to its entities), read from
--     ifcopenshell IFC4X3_ADD2 by etl/manifest.py; aim_* types state their own. Empty = no IFC check at
--     that end (object_type rule only).
--   * relationship_types.ifc_check: 'off' | 'warn' | 'enforce'.
--   * relationship_ifc_end_ok(ifc_type, allowed): the end passes when allowed is empty or ifc_type is one
--     of the allowed classes or a subtype (entity_is_a, D-195).
--   * v_relationship_ifc_violations: every edge end that fails, with the reason.
--   * Document nodes without ifc_type get IfcDocumentInformation (decision B: object_type document is
--     IfcDocumentInformation); etl/doc_upload.py sets it from now on.
--   * rel_assigns_to_actor also allows object_type 'actor' at the From end (PLATFORM.md 5.3: the IFC From
--     end is an IfcActor node whose TheActor is the person or organisation).
-- Test: supabase/tests/relationship_ifc_types.sql. Drift: etl/tests/test_manifest_ifc_types.py.

alter table public.relationship_types
  add column from_ifc_types text[] not null default '{}',
  add column to_ifc_types   text[] not null default '{}',
  add column ifc_check      text   not null default 'off',
  add constraint relationship_types_ifc_check check (ifc_check in ('off', 'warn', 'enforce'));

comment on column public.relationship_types.from_ifc_types is
  'D-196: allowed IFC classes of the from_id node (subtypes pass); empty = no IFC check';
comment on column public.relationship_types.to_ifc_types is
  'D-196: allowed IFC classes of the to_id node (subtypes pass); empty = no IFC check';
comment on column public.relationship_types.ifc_check is
  'D-196: off | warn | enforce, how relationships_validate applies the IFC end types';

