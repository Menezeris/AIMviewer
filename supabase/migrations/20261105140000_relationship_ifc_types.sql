-- One end passes the IFC rule.
create or replace function public.relationship_ifc_end_ok(p_ifc_type text, p_allowed text[])
returns boolean
language sql
stable
set search_path = public
as $$
  select cardinality(p_allowed) = 0
      or exists (select 1 from unnest(p_allowed) a where entity_is_a(p_ifc_type, a));
$$;

-- Report: every edge end that fails the IFC rule. A classification end (to_is_classification) is a
-- classification_references row = IfcClassificationReference.
create or replace view public.v_relationship_ifc_violations as
select r.id as relationship_id,
       r.rel_type,
       m.ifc_check,
       r.valid_until is null as active,
       e.edge_end,
       e.node_id,
       e.object_type,
       e.ifc_type,
       e.allowed,
       case
         when e.ifc_type is null then 'missing ifc_type'
         when not exists (select 1 from entity_types t where t.ifc_class = e.ifc_type) then 'unknown ifc_type'
         else 'not a subtype of an allowed type'
       end as reason,
       r.source,
       r.project_id
  from relationships r
  join relationship_types m on m.rel_type = r.rel_type
  left join objects f on f.id = r.from_id
  left join objects t on t.id = r.to_id and not m.to_is_classification
  cross join lateral (values
    ('from', r.from_id, f.object_type, f.ifc_type, m.from_ifc_types),
    ('to', r.to_id, t.object_type,
     case when m.to_is_classification then 'IfcClassificationReference' else t.ifc_type end,
     m.to_ifc_types)
  ) as e(edge_end, node_id, object_type, ifc_type, allowed)
 where not relationship_ifc_end_ok(e.ifc_type, e.allowed);

revoke all on function public.relationship_ifc_end_ok(text, text[]) from public, anon, authenticated;
revoke all on public.v_relationship_ifc_violations from anon, authenticated;

